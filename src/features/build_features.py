"""Leakage-aware, deterministic feature engineering."""
import numpy as np
import pandas as pd

from src.features.feature_policy import (
    TARGET, get_candidate_features, validate_feature_policy
)

def build_feature_frame(df: pd.DataFrame):
    """Return X, y, and feature metadata without fitting any preprocessing.

    Derived features use only candidate input columns expected to be known
    when an order is placed / prepared for dispatch. Confirm that assumption
    with the dataset owner before production use.
    """
    if TARGET not in df.columns:
        raise ValueError(f"Required target column {TARGET!r} is missing.")

    features = get_candidate_features(df.columns)
    validate_feature_policy(features)
    if not features:
        raise ValueError("No approved candidate features were found in the dataset.")

    X = df[features].copy()
    y_numeric = pd.to_numeric(df[TARGET], errors="coerce")
    valid_target = y_numeric.isin([0, 1])
    # Return only rows with valid binary labels. Invalid/missing labels are not
    # silently converted into a class.
    X = X.loc[valid_target].copy()
    y = y_numeric.loc[valid_target].astype("int8").copy()

    # Normalize whitespace and treat blank text as missing.
    for col in X.select_dtypes(include=["object", "string"]).columns:
        X[col] = X[col].map(lambda value: value.strip() if isinstance(value, str) else value)
        X[col] = X[col].replace("", np.nan)

    # Convert known numeric candidates even if pandas read them as text.
    numeric_candidates = [
        "Days for shipment (scheduled)", "Category Id", "Department Id",
        "Latitude", "Longitude", "Order Item Discount",
        "Order Item Discount Rate", "Order Item Product Price",
        "Order Item Quantity", "Product Price",
    ]
    for col in numeric_candidates:
        if col in X.columns:
            X[col] = pd.to_numeric(X[col], errors="coerce")

    # Feature engineering: safe division with explicit zero/missing handling.
    scheduled = pd.to_numeric(
        X["Days for shipment (scheduled)"], errors="coerce"
    ) if "Days for shipment (scheduled)" in X else None
    quantity = pd.to_numeric(
        X["Order Item Quantity"], errors="coerce"
    ) if "Order Item Quantity" in X else None

    if scheduled is not None and quantity is not None:
        denominator = scheduled.where(scheduled > 0)
        X["shipping_pressure_index"] = quantity / denominator

    if "Shipping Mode" in X.columns:
        mode = X["Shipping Mode"].astype("string").str.strip().str.lower()
        X["is_express_shipping"] = mode.isin(["same day", "first class", "express"]).astype("int8")

    if "Order Item Discount" in X.columns and "Order Item Product Price" in X.columns:
        price = pd.to_numeric(X["Order Item Product Price"], errors="coerce")
        discount = pd.to_numeric(X["Order Item Discount"], errors="coerce")
        safe_price = price.where(price > 0)
        X["discount_to_item_price_ratio"] = discount / safe_price

    if quantity is not None:
        # A transparent proxy, not a true operational complexity measurement.
        X["log_order_quantity"] = np.log1p(quantity.clip(lower=0))

    # Replace infinite values generated by invalid numeric inputs with missing;
    # imputers in the pipeline handle these during model fitting.
    X = X.replace([np.inf, -np.inf], np.nan)
    metadata = {
        "target": TARGET,
        "candidate_features": features,
        "engineered_features": [
            col for col in [
                "shipping_pressure_index", "is_express_shipping",
                "discount_to_item_price_ratio", "log_order_quantity"
            ] if col in X.columns
        ],
        "rows_before_target_filter": int(len(df)),
        "rows_after_target_filter": int(len(X)),
        "rows_dropped_for_invalid_target": int(len(df) - len(X)),
    }
    return X, y, metadata
